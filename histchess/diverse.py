"""Template-diversified, rule-verified counterfactual histories.

All output is replayed and checked by ``core.pair_from_moves``.  Families are
*mechanisms*, not separate hardcoded sets of outcomes.  Family-held-out splits
are designed to test transfer beyond histories generated by the same recipe.
This is still a synthetic benchmark, not a real-game evaluation.
"""
from __future__ import annotations

import collections
import random

import chess

from .core import (TASKS, CAST_POS, CAST_NEG, EP_POS, EP_NEG, HALF_POS,
                   HALF_NEG, REP_POS, REP_NEG, digest, pair_from_moves)

FAMILIES = {
    "castling": ("rook_g1_return", "king_e2_return", "rook_h2_return"),
    "en_passant": ("quiet_vs_double", "two_black_doubles", "black_captures_white_double"),
    "halfmove": ("both_pawns_last", "white_pawn_penultimate", "black_pawn_last"),
    "repetition": ("legacy_two_cycles", "interleaved_reverse", "interleaved_forward"),
}


def _prefix(rng, pos, neg, maximum=4):
    """Add common, noncapturing pawn development on unused files.

    Files that any template move touches are excluded, including knight
    landing squares.  Unrelated legal trajectories are still verified later.
    """
    all_moves = tuple(pos) + tuple(neg)
    # A pawn that the core sequence moves must remain at its original square.
    blocked = {uci[0] for uci in all_moves
               if uci[0] == uci[2] and uci[1] in "27"}
    # Do not occupy a knight's required destination while making a prefix.
    landings = {uci[2:4] for uci in all_moves}
    board = chess.Board()
    history = []
    for _ in range(2 * rng.randint(0, maximum)):
        available = []
        for move in board.legal_moves:
            if (board.piece_type_at(move.from_square) == chess.PAWN
                    and chess.square_name(move.from_square)[0] not in blocked
                    and chess.square_name(move.to_square) not in landings
                    and not board.is_capture(move) and not move.promotion):
                available.append(move)
        if not available:
            raise ValueError("Shared prefix has no legal pawn move")
        move = rng.choice(available)
        board.push(move)
        history.append(move.uci())
    return tuple(history)


def _castling(rng, family):
    if family == "rook_g1_return":
        from .core import castling_suffix
        return castling_suffix(rng, CAST_POS, CAST_NEG, rng.randint(1, 14))
    if family == "king_e2_return":
        # Both histories end with king on e1, knight on g1 and identical
        # pawn/knight pieces; only the king's prior move removes castling rights.
        pos = ("e2e4", "g8f6", "g1f3", "f6g8", "f3g1", "g8f6")
        neg = ("e2e4", "g8f6", "e1e2", "f6g8", "e2e1", "g8f6")
    elif family == "rook_h2_return":
        # Move the h-pawn first so the rook can legally return via h2.
        pos = ("h2h3", "g8f6", "g1f3", "f6g8", "f3g1", "g8f6")
        neg = ("h2h3", "g8f6", "h1h2", "f6g8", "h2h1", "g8f6")
    else:
        raise ValueError(family)
    from .core import castling_suffix
    return castling_suffix(rng, pos, neg, rng.randint(1, 14))


def _ep(rng, family):
    if family == "black_captures_white_double":
        # Side-to-move is black; the final move in BOTH histories is a white
        # two-square pawn push. Only one grants black a legal EP capture.
        black = rng.choice("bcdefg")
        near = rng.choice([f for f in "abcdefgh"
                           if abs(ord(f) - ord(black)) == 1])
        far = rng.choice([f for f in "ah" if abs(ord(f)-ord(black)) > 1])
        wk = rng.choice(("g1f3", "b1c3"))
        near_white = f"{near}2{near}4"
        far_white = f"{far}2{far}4"
        bp2 = f"{black}7{black}5"
        bp1 = f"{black}5{black}4"
        pos = (far_white, bp2, wk, bp1, near_white)
        neg = (near_white, bp2, wk, bp1, far_white)
    else:
        white = rng.choice("bcdefg")
        near = rng.choice([f for f in "abcdefgh"
                           if abs(ord(f) - ord(white)) == 1])
        wp2, wp1 = f"{white}2{white}4", f"{white}4{white}5"
        bp2 = f"{near}7{near}5"
        if family == "quiet_vs_double":
            quiet = rng.choice([f for f in "abcdefgh" if f not in (near, white)])
            q = f"{quiet}7{quiet}6"
            pos = (wp2, q, wp1, bp2)
            neg = (wp2, bp2, wp1, q)
        elif family == "two_black_doubles":
            far = rng.choice([f for f in "ah" if abs(ord(f)-ord(white))>1 and f != near])
            bd_far = f"{far}7{far}5"
            bk = rng.choice(("g8f6", "b8c6"))
            wk = rng.choice(("g1f3", "b1c3"))
            pos = (wp2, bk, wp1, bd_far, wk, bp2)
            neg = (wp2, bk, wp1, bp2, wk, bd_far)
        else:
            raise ValueError(family)
    prefix = _prefix(rng, pos, neg)
    return prefix + pos, prefix + neg


def _halfmove(rng, family):
    white = rng.choice("abcdefgh")
    black = rng.choice("abcdefgh")
    wp = f"{white}2{white}4"
    bp = f"{black}7{black}5"
    wk, wk_rev = rng.choice((("g1f3", "f3g1"), ("b1c3", "c3b1"),
                             ("g1h3", "h3g1"), ("b1a3", "a3b1")))
    bk, bk_rev = rng.choice((("g8f6", "f6g8"), ("b8c6", "c6b8"),
                             ("g8h6", "h6g8"), ("b8a6", "a6b8")))
    pos = (wp, bp, wk, bk, wk_rev, bk_rev)
    if family == "both_pawns_last":
        neg = (wk, bk, wk_rev, bk_rev, wp, bp)
    elif family == "white_pawn_penultimate":
        neg = (wk, bk, wk_rev, bp, wp, bk_rev)
    elif family == "black_pawn_last":
        neg = (wp, bk, wk, bk_rev, wk_rev, bp)
    else:
        raise ValueError(family)
    prefix = _prefix(rng, pos, neg)
    return prefix + pos, prefix + neg


def _repetition(rng, family):
    if family == "legacy_two_cycles":
        pos, neg = REP_POS, REP_NEG
    else:
        wknights = (("g1f3", "f3g1"), ("g1h3", "h3g1"),
                    ("b1c3", "c3b1"), ("b1a3", "a3b1"))
        bknights = (("g8f6", "f6g8"), ("g8h6", "h6g8"),
                    ("b8c6", "c6b8"), ("b8a6", "a6b8"))
        a, ar = rng.choice(wknights)
        b, br = rng.choice(bknights)
        c, cr = rng.choice([p for p in wknights if p[0][0:2] != a[:2]])
        d, dr = rng.choice([p for p in bknights if p[0][0:2] != b[:2]])
        pos = (a, b, ar, br, a, b, ar, br)
        if family == "interleaved_reverse":
            neg = (c, d, a, b, ar, br, cr, dr)
        elif family == "interleaved_forward":
            neg = (a, b, c, d, cr, dr, ar, br)
        else:
            raise ValueError(family)
    prefix = _prefix(rng, pos, neg)
    return prefix + pos, prefix + neg


def generate_diverse(count_per_task=80, seed=3101,
                     max_attempt_multiplier=250, split_strategy="family"):
    """Generate balanced families and optional out-of-family validation/test.

    ``family``: entire generation mechanisms are withheld from training.
    ``board``: disjoint observable-board groups but shared generator families.
    """
    if split_strategy not in ("family", "board"):
        raise ValueError("split_strategy must be 'family' or 'board'")
    if count_per_task < 3:
        raise ValueError("At least 3 pairs per task are required")
    rng = random.Random(seed)
    result, used, failures = [], set(), collections.Counter()
    functions = {"castling":_castling, "en_passant":_ep,
                 "halfmove":_halfmove, "repetition":_repetition}
    for task in TASKS:
        families = FAMILIES[task]
        for family_index, family in enumerate(families):
            target = count_per_task // len(families) + (family_index < count_per_task % len(families))
            made = 0
            for _ in range(target * max_attempt_multiplier):
                if made >= target:
                    break
                try:
                    pos, neg = functions[task](rng, family)
                    pair = pair_from_moves(task, pos, neg)
                    # A board can appear under multiple chess tasks. Validation
                    # requires observable boards to be disjoint across *all*
                    # task/split combinations, not just within each task.
                    # Enforce that invariant at generation time so a family
                    # held out for one task cannot leak through another task.
                    novelty = pair["board_key"]
                    if novelty in used:
                        failures[f"{task}:{family}:duplicate_board"] += 1
                        continue
                    used.add(novelty)
                    pair["generator_family"] = family
                    if split_strategy == "family":
                        pair["split"] = ("train", "validation", "test")[family_index]
                    else:
                        bucket = int(digest(f"{seed}|{pair['board_key']}")[:8], 16) % 100
                        pair["split"] = "train" if bucket < 70 else "validation" if bucket < 85 else "test"
                    result.append(pair)
                    made += 1
                except (ValueError, AssertionError) as exc:
                    failures[f"{task}:{family}:{type(exc).__name__}"] += 1
                    continue
            if made != target:
                raise RuntimeError(f"Only generated {made}/{target} pairs for {task}/{family}; "
                                   f"failures: {dict(failures)}")
    return result, dict(failures)
